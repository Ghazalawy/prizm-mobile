/** All registered widget keys, sorted by sortOrder */
export const ALL_WIDGET_KEYS = Object.values(WIDGET_REGISTRY)
  .sort((a, b) => a.sortOrder - b.sortOrder)
  .map((w) => w.key);

/** Get a widget definition by key. Returns undefined for unknown keys. */
export function getWidget(key: string): WidgetDef | undefined {
  return WIDGET_REGISTRY[key];
}

/** List all widgets that the given permission checker allows. */
export function getVisibleWidgets(
  hasAnyPermission: (feature: string) => boolean
): WidgetDef[] {
  return Object.values(WIDGET_REGISTRY)
    .sort((a, b) => a.sortOrder - b.sortOrder)
    .filter((w) => !w.permissionFeature || hasAnyPermission(w.permissionFeature));
}

/**
 * Dashboard Widget Registry — single source of truth for every widget the
 * dashboard can render. The registry drives:
 *
 *   1. Which cards appear in the admin workbench palette
 *   2. Which cards the dashboard screen can render
 *   3. The seed data for tbldashboard_widgets on the backend
 *   4. Permission gating (only show if user has feature access)
 *
 * To add a new module widget: add an entry here, create its query hook,
 * and it shows up everywhere automatically.
 */

export type WidgetSize = "1x1" | "2x1" | "1x2" | "2x2";
export type WidgetComponentType = "stat" | "chart" | "list" | "action";

export type WidgetDef = {
  key: string;
  title: string;
  icon: string;
  color: string;
  componentType: WidgetComponentType;
  defaultSize: WidgetSize;
  sizes: WidgetSize[];
  /** Perfex permission feature key — null means always visible */
  permissionFeature: string | null;
  /** Source module for grouping in the palette */
  module: string;
  /** Route to navigate when tapped */
  route: string;
  /** Sort order in the palette (lower = first) */
  sortOrder: number;
};

